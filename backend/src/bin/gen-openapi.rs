//! Generates the OpenAPI specification for PudimFinance.
//!
//! Usage:
//!   cargo run --bin gen-openapi > ../api/openapi/openapi.json
//!
//! This binary is a build-time tool that outputs the full OpenAPI 3.1 spec
//! derived from utoipa annotations on the backend's handlers and schemas.

use serde_json::Value;
use utoipa::OpenApi;

fn main() {
    let spec = backend::ApiDoc::openapi();
    let mut json = serde_json::to_value(&spec).expect("Failed to serialize OpenAPI spec");

    // OpenAPI extension fields use the "x-" prefix and are ignored by validators.
    json["x-generator"] = Value::String(
        concat!(
            "Auto-generated by backend/src/bin/gen-openapi.rs ",
            "from utoipa annotations in backend/src/openapi.rs"
        )
        .into(),
    );

    println!(
        "{}",
        serde_json::to_string_pretty(&json).expect("Failed to serialize OpenAPI spec")
    );
}
